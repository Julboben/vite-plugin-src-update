import fs from "node:fs/promises";
import path from "node:path";

export type CommentFormatter = (comment: string) => string;

const SIGNATURE = "generated by vite-plugin-src-update";

export const HEADER_COMMENT = `IMPORTANT: This file is automatically ${SIGNATURE}.
Do not modify it directly, as any changes will be overwritten by the next build.`;

const htmlComment: CommentFormatter = (c) => `<!-- ${c} -->`;
const razorComment: CommentFormatter = (c) => `@* ${c} *@`;
const aspxComment: CommentFormatter = (c) => `<%-- ${c} --%>`;
const jinjaComment: CommentFormatter = (c) => `{# ${c} #}`;
const erbComment: CommentFormatter = (c) => `<%# ${c} %>`;
const handlebarsComment: CommentFormatter = (c) => `{{!-- ${c} --}}`;

export const DEFAULT_COMMENT_TEMPLATES: Record<string, CommentFormatter> = {
  ".html": htmlComment,
  ".htm": htmlComment,
  ".php": (c) => `<?php /* ${c} */ ?>`,
  ".liquid": (c) => `{% comment %}\n${c}\n{% endcomment %}`,
  ".hbs": handlebarsComment,
  ".handlebars": handlebarsComment,
  ".mustache": (c) => `{{! ${c} }}`,
  ".cshtml": razorComment,
  ".vbhtml": razorComment,
  ".razor": razorComment,
  ".aspx": aspxComment,
  ".ascx": aspxComment,
  ".master": aspxComment,
  ".twig": jinjaComment,
  ".njk": jinjaComment,
  ".jinja": jinjaComment,
  ".j2": jinjaComment,
  ".ejs": erbComment,
  ".erb": erbComment,
};

const RAZOR_EXTENSIONS = new Set([".cshtml", ".vbhtml", ".razor"]);

export interface TemplateFormat {
  /** Header comment, already formatted for the template language. */
  header: string;
  /** Escapes plain text (URLs, inline code) for the template language. */
  escape: (text: string) => string;
}

export function getTemplateFormat(
  filePath: string,
  commentTemplates: Record<string, CommentFormatter> = {}
): TemplateFormat {
  const ext = path.extname(filePath).toLowerCase();
  const formatter =
    commentTemplates[ext] ?? DEFAULT_COMMENT_TEMPLATES[ext] ?? htmlComment;
  return {
    header: formatter(HEADER_COMMENT),
    // Razor treats `@` (e.g. in `/@vite/client`) as the start of C# code.
    escape: RAZOR_EXTENSIONS.has(ext)
      ? (text) => text.replaceAll("@", "@@")
      : (text) => text,
  };
}

export interface WriteTemplateOptions {
  filePath: string;
  header: string;
  tags: string[];
  marker: string;
  force: boolean;
}

/** What `writeTemplate` did, for logging. */
export type WriteResult = "written" | "unchanged";

// Serialise writes per file, so several plugin instances can share one
// template (e.g. separate markers for head and body).
const queues = new Map<string, Promise<unknown>>();

export function writeTemplate(options: WriteTemplateOptions): Promise<WriteResult> {
  const previous = queues.get(options.filePath) ?? Promise.resolve();
  const next = previous.catch(() => {}).then(() => write(options));
  queues.set(options.filePath, next);
  return next;
}

async function write({
  filePath,
  header,
  tags,
  marker,
  force,
}: WriteTemplateOptions): Promise<WriteResult> {
  const current = await readIfExists(filePath);
  const content = current === null
    ? renderFile(header, tags, "\n")
    : updateContent(current, { filePath, header, tags, marker, force });

  // Skip no-op writes so backend file-watchers (Stencil CLI, dotnet watch,
  // Shopify CLI, etc.) don't trigger needless reloads.
  if (content === current) return "unchanged";

  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, content);
  return "written";
}

/** Computes the new file content from the current one. Exported for testing. */
export function updateContent(
  current: string,
  { filePath, header, tags, marker, force }: WriteTemplateOptions
): string {
  const eol = current.includes("\r\n") ? "\r\n" : "\n";
  const lines = current.split(/\r?\n/);
  const start = lines.findIndex((line) => line.includes(`${marker}:start`));
  const end = lines.findIndex(
    (line, i) => i > start && line.includes(`${marker}:end`)
  );

  if (start !== -1 && end !== -1) {
    const indent = lines[start].match(/^\s*/)?.[0] ?? "";
    return [
      ...lines.slice(0, start + 1),
      ...tags.map((tag) => indent + tag),
      ...lines.slice(end),
    ].join(eol);
  }

  if (start !== -1) {
    throw new Error(
      `${filePath} has a "${marker}:start" marker but no "${marker}:end" marker after it.`
    );
  }

  if (!force && current.trim() !== "" && !current.includes(SIGNATURE)) {
    throw new Error(
      `Refusing to overwrite ${filePath}: it wasn't generated by vite-plugin-src-update. ` +
        `Add "${marker}:start" and "${marker}:end" markers (in comments) where the tags should go, ` +
        `point templateFilePath at a dedicated file, or set force: true.`
    );
  }

  return renderFile(header, tags, eol);
}

function renderFile(header: string, tags: string[], eol: string): string {
  return [header, ...tags].join("\n").replaceAll("\n", eol) + eol;
}

async function readIfExists(filePath: string): Promise<string | null> {
  try {
    return await fs.readFile(filePath, "utf8");
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return null;
    throw err;
  }
}
