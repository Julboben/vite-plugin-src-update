/** Platforms with built-in support. */
export type Platform =
  /** BigCommerce Stencil: `{{cdn '/dist/main.js'}}` */
  | "bigcommerce"
  /** Shopify: `{{ 'main.js' | asset_url }}` */
  | "shopify"
  /** ASP.NET MVC Razor (`.cshtml`): `@Url.Content("~/dist/main.js")` */
  | "razor"
  /** ASP.NET Web Forms (`.aspx`, `.master`): `<%= ResolveUrl("~/dist/main.js") %>` */
  | "webforms";

/** @deprecated Use `Platform`. */
export type AssetUrlPreset = Platform;

/**
 * Receives the public URL (`base` + file name) and the file name relative to
 * `build.outDir`, and returns what should be written into the attribute.
 */
export type AssetUrlFunction = (url: string, fileName: string) => string;

export interface VitePluginSrcUpdateOptions {
  // Essentials

  /** Path to the template file to update, relative to the current working directory. */
  templateFilePath: string;
  /**
   * Entry points to include in this template, relative to the Vite root.
   * A directory includes every script and style file inside it.
   *
   * When Vite has no build input configured, the inputs of all templates
   * become the build input. Without `input`, the template gets the
   * configured build input.
   */
  input?: string[];
  /**
   * The platform that renders the template. Wraps built asset URLs in its
   * helper (e.g. Shopify's `asset_url`) and fills in Vite options you
   * haven't set: `base: "./"` for `"bigcommerce"` and `"shopify"`, plus
   * `build.assetsDir: ""` and CORS for `*.myshopify.com` for `"shopify"`.
   */
  platform?: Platform;

  // Built asset URLs

  /**
   * Public URL prefix for built assets, e.g. `/dist/` or `https://cdn.example.com/`.
   * Defaults to Vite's `base` when you set it explicitly, otherwise to
   * `/<outDir relative to root>/`.
   */
  base?: string;
  /**
   * Custom wrapper for built asset URLs; takes precedence over the
   * `platform` helper. Passing a platform name here is deprecated, use `platform`.
   */
  assetUrl?: AssetUrlFunction | Platform;

  // Generated tags

  /**
   * Extra attributes added to every generated tag, inserted verbatim so
   * template expressions work, e.g. `{ nonce: "@ViewBag.Nonce", crossorigin: true }`.
   */
  attributes?: Record<string, string | boolean>;
  /** Add `integrity="sha384-…"` to built scripts and stylesheets. Defaults to `false`. */
  integrity?: boolean;
  /** Emit `<link rel="modulepreload">` for chunks imported by entries. Defaults to `true` unless `build.modulePreload` is `false`. */
  modulePreload?: boolean;
  /** Inject Vite's HMR client (`@vite/client`) in dev so backend-served pages get HMR. Defaults to `true`. */
  injectClient?: boolean;
  /**
   * Extra tags written after the HMR client in dev only, e.g. Shopify's theme
   * hot reload script. Pass a function to build them from the dev server origin.
   */
  devTags?: string[] | ((origin: string) => string[]);

  // Template file

  /**
   * Name of the markers used to update only part of an existing file.
   * The plugin replaces everything between lines containing `<marker>:start`
   * and `<marker>:end`. Defaults to `"vite-plugin-src-update"`.
   */
  marker?: string;
  /** Overwrite the template even if it wasn't generated by this plugin and has no markers. Defaults to `false`. */
  force?: boolean;
  /** Per-extension formatters for the auto-generated header comment, merged with the defaults. */
  commentTemplates?: Record<string, (comment: string) => string>;

  // Debugging

  /** Log the output instead of writing the template file. Defaults to `false`. */
  dryRun?: boolean;
  /** Log additional diagnostic information. Defaults to `false`. */
  verbose?: boolean;

  // Deprecated

  /**
   * @deprecated Use `base`. Kept for 1.x compatibility: prefixes asset paths
   * exactly as given (no leading slash is added).
   */
  outDir?: string;
  /** @deprecated Use `platform: "bigcommerce"`. */
  cdn?: boolean;
}
