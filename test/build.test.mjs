import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { describe, test } from "node:test";
import srcUpdate from "../dist/index.js";
import { exists, fixture, read, runBuild, tagsOf } from "./helpers.mjs";

describe("build", () => {
  test("writes stylesheets, preloads and scripts in that order", async () => {
    const root = await fixture();
    const file = path.join(root, "template.html");
    await runBuild(root, { templateFilePath: file });

    const content = await read(file);
    assert.match(content, /^<!-- IMPORTANT: This file is automatically generated by vite-plugin-src-update/);
    assert.deepEqual(
      tagsOf(content).map((tag) => tag.replace(/-[\w-]{8}\./, ".")),
      [
        `<link rel="stylesheet" href="/dist/assets/main.css">`,
        `<link rel="stylesheet" href="/dist/assets/entry.css">`,
        `<link rel="modulepreload" href="/dist/assets/shared.js">`,
        `<script type="module" src="/dist/assets/main.js"></script>`,
        `<script type="module" src="/dist/assets/second.js"></script>`,
      ]
    );
  });

  test("only includes the configured inputs in each template", async () => {
    const root = await fixture();
    const scripts = path.join(root, "scripts.html");
    const styles = path.join(root, "styles.html");
    await runBuild(root, [
      { templateFilePath: scripts, input: ["src/second.js"] },
      { templateFilePath: styles, input: ["src/entry.css"] },
    ]);

    const scriptTags = tagsOf(await read(scripts));
    assert.equal(scriptTags.length, 2);
    assert.match(scriptTags[0], /rel="modulepreload" href="\/dist\/assets\/shared-/);
    assert.match(scriptTags[1], /src="\/dist\/assets\/second-/);

    const styleTags = tagsOf(await read(styles));
    assert.equal(styleTags.length, 1);
    assert.match(styleTags[0], /href="\/dist\/assets\/entry-.*\.css"/);
  });

  test("warns about inputs that are not in the bundle", async () => {
    const root = await fixture();
    const messages = await runBuild(root, {
      templateFilePath: path.join(root, "t.html"),
      input: ["src/missing.js"],
    });
    assert.ok(messages.some((m) => m.includes(`Input "src/missing.js" was not found`)));
  });

  describe("base URL", () => {
    const firstUrl = async (root, file) =>
      tagsOf(await read(file))[0].match(/(?:href|src)="([^"]+)"/)[1];

    test("uses the base option", async () => {
      const root = await fixture();
      const file = path.join(root, "t.html");
      await runBuild(root, { templateFilePath: file, base: "https://cdn.example.com/theme" });
      assert.match(await firstUrl(root, file), /^https:\/\/cdn\.example\.com\/theme\/assets\/main-/);
    });

    test("uses Vite's base when it is set explicitly", async () => {
      const root = await fixture();
      const file = path.join(root, "t.html");
      await runBuild(root, { templateFilePath: file }, { base: "/static/" });
      assert.match(await firstUrl(root, file), /^\/static\/assets\/main-/);
    });

    test("keeps the deprecated outDir option working as in 1.x", async () => {
      const root = await fixture();
      const file = path.join(root, "t.html");
      const messages = await runBuild(root, { templateFilePath: file, outDir: "vite-build" });
      assert.match(await firstUrl(root, file), /^vite-build\/assets\/main-/);
      assert.ok(messages.some((m) => m.includes("outDir is deprecated, use base.")));
    });

    test("warns when build.outDir is outside the root", async () => {
      const root = await fixture();
      const file = path.join(root, "t.html");
      const messages = await runBuild(
        root,
        { templateFilePath: file },
        { build: { outDir: "../outside-dist", emptyOutDir: true } }
      );
      assert.match(await firstUrl(root, file), /^\/assets\/main-/);
      assert.ok(messages.some((m) => m.includes(`Set the "base" option`)));
    });
  });

  describe("platform and assetUrl", () => {
    const cases = {
      bigcommerce: /^<link rel="stylesheet" href="\{\{cdn '\.?\/dist\/(?:assets\/)?main-[\w-]+\.css'\}\}">$/,
      shopify: /^<link rel="stylesheet" href="\{\{ 'main-[\w-]+\.css' \| asset_url \}\}">$/,
      razor: /^<link rel="stylesheet" href="@Url\.Content\("~\/dist\/assets\/main-[\w-]+\.css"\)">$/,
      webforms: /^<link rel="stylesheet" href="<%= ResolveUrl\("~\/dist\/assets\/main-[\w-]+\.css"\) %>">$/,
    };
    const firstTag = async (pluginOptions, viteConfig) => {
      const root = await fixture();
      const file = path.join(root, "t.html");
      const messages = await runBuild(root, { templateFilePath: file, ...pluginOptions }, viteConfig);
      return { tag: tagsOf(await read(file))[0], messages };
    };

    for (const [platform, expected] of Object.entries(cases)) {
      test(`platform: "${platform}"`, async () => {
        const { tag, messages } = await firstTag({ platform });
        assert.match(tag, expected);
        assert.ok(!messages.some((m) => m.includes("deprecated")));
      });
    }

    test("a custom assetUrl overrides the platform helper but keeps its defaults", async () => {
      const { tag } = await firstTag({
        platform: "shopify",
        assetUrl: (url, fileName) => `${url}|${fileName}`,
      });
      // Flat output (assetsDir: "") comes from the shopify platform defaults.
      assert.match(tag, /href="\/dist\/main-[\w-]+\.css\|main-[\w-]+\.css"/);
    });

    test("deprecated assetUrl: \"<platform>\" still works and warns", async () => {
      const { tag, messages } = await firstTag({ assetUrl: "razor" });
      assert.match(tag, cases.razor);
      assert.ok(messages.some((m) => m.includes(`assetUrl: "razor" is deprecated, use platform: "razor"`)));
    });

    test("deprecated cdn: true still works and warns", async () => {
      const { tag, messages } = await firstTag({ cdn: true });
      assert.match(tag, cases.bigcommerce);
      assert.ok(messages.some((m) => m.includes(`cdn is deprecated, use platform: "bigcommerce"`)));
    });

    test("warns when the shopify platform is used with an assets subfolder", async () => {
      const { messages } = await firstTag({ platform: "shopify" }, { build: { assetsDir: "assets" } });
      assert.ok(messages.some((m) => m.includes("flat folder")));
    });

    test("rejects unknown platforms", () => {
      assert.throws(
        () => srcUpdate({ templateFilePath: "t.html", platform: "magento" }),
        /Unknown platform "magento"/
      );
    });
  });

  test("warns about unknown options", async () => {
    const root = await fixture();
    const messages = await runBuild(root, {
      templateFilePath: path.join(root, "t.html"),
      templatePath: "typo.html",
    });
    assert.ok(messages.some((m) => m.includes(`Unknown option "templatePath" is ignored.`)));
  });

  test("adds attributes and integrity hashes", async () => {
    const root = await fixture();
    const file = path.join(root, "t.html");
    await runBuild(root, {
      templateFilePath: file,
      integrity: true,
      attributes: { nonce: "{{ nonce }}", "data-turbo-track": "reload" },
    });
    for (const tag of tagsOf(await read(file))) {
      assert.match(tag, / integrity="sha384-[A-Za-z0-9+/=]{64}" crossorigin nonce="\{\{ nonce \}\}" data-turbo-track="reload"/);
    }
  });

  test("collects every output, like @vitejs/plugin-legacy's modern + legacy builds", async () => {
    const root = await fixture();
    const file = path.join(root, "t.html");
    await runBuild(
      root,
      { templateFilePath: file, input: ["src/second.js"] },
      {
        build: {
          rollupOptions: {
            input: { second: path.join(root, "src/second.js") },
            output: [
              { entryFileNames: "[name]-legacy.js", chunkFileNames: "[name]-legacy.js" },
              { entryFileNames: "[name].js", chunkFileNames: "[name].js" },
            ],
          },
        },
      }
    );
    assert.deepEqual(tagsOf(await read(file)), [
      `<script type="module" src="/dist/second.js"></script>`,
      `<script nomodule crossorigin id="vite-legacy-entry" data-src="/dist/second-legacy.js">System.import(document.getElementById('vite-legacy-entry').getAttribute('data-src'))</script>`,
    ]);
  });

  test("respects modulePreload: false", async () => {
    const root = await fixture();
    const file = path.join(root, "t.html");
    await runBuild(root, { templateFilePath: file, modulePreload: false });
    assert.ok(!(await read(file)).includes("modulepreload"));
  });

  test("does not touch the template for SSR builds", async () => {
    const root = await fixture();
    const file = path.join(root, "t.html");
    await runBuild(root, { templateFilePath: file }, { build: { ssr: "src/main.js", rollupOptions: {} } });
    assert.equal(await exists(file), false);
  });

  test("dryRun logs instead of writing", async () => {
    const root = await fixture();
    const file = path.join(root, "t.html");
    const messages = await runBuild(root, { templateFilePath: file, dryRun: true });
    assert.equal(await exists(file), false);
    assert.ok(messages.some((m) => m.includes("[dry run]") && m.includes("<script")));
  });

  test("skips the write when nothing changed", async () => {
    const root = await fixture();
    const file = path.join(root, "t.html");
    await runBuild(root, { templateFilePath: file });
    const before = await fs.stat(file);
    await new Promise((resolve) => setTimeout(resolve, 20));
    await runBuild(root, { templateFilePath: file });
    assert.equal((await fs.stat(file)).mtimeMs, before.mtimeMs);
  });

  test("creates missing directories", async () => {
    const root = await fixture();
    const file = path.join(root, "snippets/nested/vite.liquid");
    await runBuild(root, { templateFilePath: file });
    assert.match(await read(file), /^\{% comment %\}/);
  });

  test("fails the build when the template can't be written", async () => {
    const root = await fixture();
    await assert.rejects(
      runBuild(root, { templateFilePath: path.join(root, "src") }),
      /Failed to update .*src: EISDIR/
    );
  });
});
