import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { describe, test } from "node:test";
import { fixture, read, runBuild, tagsOf } from "./helpers.mjs";

const input = ["src/second.js"];

describe("template file", () => {
  test("only replaces the content between markers", async () => {
    const root = await fixture();
    const file = path.join(root, "layout.html");
    await fs.writeFile(
      file,
      [
        "<html>",
        "  <head>",
        "    <!-- vite-plugin-src-update:start -->",
        "    <script>old</script>",
        "    <!-- vite-plugin-src-update:end -->",
        "  </head>",
        "</html>",
        "",
      ].join("\n")
    );
    await runBuild(root, { templateFilePath: file, input });

    const lines = (await read(file)).split("\n");
    assert.equal(lines[2], "    <!-- vite-plugin-src-update:start -->");
    assert.match(lines[3], /^    <link rel="modulepreload"/);
    assert.match(lines[4], /^    <script type="module" src="\/dist\/assets\/second-/);
    assert.deepEqual(lines.slice(5), [
      "    <!-- vite-plugin-src-update:end -->",
      "  </head>",
      "</html>",
      "",
    ]);
  });

  test("supports several markers in one file", async () => {
    const root = await fixture();
    const file = path.join(root, "layout.liquid");
    await fs.writeFile(
      file,
      "{% # styles:start %}\n{% # styles:end %}\n<main></main>\n{% # scripts:start %}\n{% # scripts:end %}\n"
    );
    await runBuild(root, [
      { templateFilePath: file, input: ["src/entry.css"], marker: "styles" },
      { templateFilePath: file, input, marker: "scripts" },
    ]);

    const content = await read(file);
    assert.match(content, /styles:start %\}\n<link rel="stylesheet"[^\n]+\n\{% # styles:end/);
    assert.match(content, /scripts:start %\}\n<link rel="modulepreload"[^\n]+\n<script[^\n]+\n\{% # scripts:end/);
  });

  test("keeps Windows line endings", async () => {
    const root = await fixture();
    const file = path.join(root, "_Layout.cshtml");
    await fs.writeFile(file, "<head>\r\n@* vite-plugin-src-update:start *@\r\n@* vite-plugin-src-update:end *@\r\n</head>\r\n");
    await runBuild(root, { templateFilePath: file, input });
    const content = await read(file);
    assert.equal(content.split("\r\n").length, 7);
    assert.ok(!/[^\r]\n/.test(content));
  });

  test("refuses to overwrite a file it didn't generate", async () => {
    const root = await fixture();
    const file = path.join(root, "theme.liquid");
    await fs.writeFile(file, "<html>{{ content_for_layout }}</html>\n");
    await assert.rejects(runBuild(root, { templateFilePath: file, input }), /Refusing to overwrite/);
    assert.equal(await read(file), "<html>{{ content_for_layout }}</html>\n");
  });

  test("overwrites a foreign file with force: true", async () => {
    const root = await fixture();
    const file = path.join(root, "theme.html");
    await fs.writeFile(file, "<p>hand written</p>\n");
    await runBuild(root, { templateFilePath: file, input, force: true });
    assert.equal(tagsOf(await read(file)).length, 2);
  });

  test("overwrites files generated by 1.x", async () => {
    const root = await fixture();
    const file = path.join(root, "vite.html");
    await fs.writeFile(
      file,
      "<!-- IMPORTANT: This component is automatically generated by vite-plugin-src-update.\nDo not attempt to modify this file directly, as any changes will be overwritten by the next build. -->\n<script></script>\n"
    );
    await runBuild(root, { templateFilePath: file, input });
    assert.equal(tagsOf(await read(file)).length, 2);
  });

  test("errors on a start marker without an end marker", async () => {
    const root = await fixture();
    const file = path.join(root, "t.html");
    await fs.writeFile(file, "<!-- vite-plugin-src-update:start -->\n");
    await assert.rejects(runBuild(root, { templateFilePath: file, input }), /no "vite-plugin-src-update:end" marker/);
  });

  describe("header comment", () => {
    const header = async (name, options = {}) => {
      const root = await fixture();
      const file = path.join(root, name);
      await runBuild(root, { templateFilePath: file, input, ...options });
      return (await read(file)).split(/<(?:link|script) /)[0];
    };

    const cases = {
      "t.liquid": /^\{% comment %\}\nIMPORTANT: [^]+\n\{% endcomment %\}\n$/,
      "t.hbs": /^\{\{!-- IMPORTANT: [^]+ --\}\}\n$/,
      "t.cshtml": /^@\* IMPORTANT: [^]+ \*@\n$/,
      "t.aspx": /^<%-- IMPORTANT: [^]+ --%>\n$/,
      "t.twig": /^\{# IMPORTANT: [^]+ #\}\n$/,
      "t.php": /^<\?php \/\* IMPORTANT: [^]+ \*\/ \?>\n$/,
      // Unknown extensions fall back to an HTML comment instead of visible text.
      "t.unknown": /^<!-- IMPORTANT: [^]+ -->\n$/,
    };
    for (const [name, expected] of Object.entries(cases)) {
      test(name, async () => assert.match(await header(name), expected));
    }

    test("custom templates extend the defaults", async () => {
      const commentTemplates = { ".tpl": (c) => `{* ${c} *}` };
      assert.match(await header("t.tpl", { commentTemplates }), /^\{\* IMPORTANT/);
      assert.match(await header("t.html", { commentTemplates }), /^<!-- IMPORTANT/);
    });
  });
});
